const TRANSITIONS = [
  "idle-slide-left",
  "idle-slide-up",
  "idle-fade",
  "idle-zoom",
  "idle-flip",
];

export function IdleScreen({ onDismiss }: { onDismiss: () => void }) {
  const [index, setIndex] = useState(0);
  const [transition, setTransition] = useState("idle-fade");
  const [key, setKey] = useState(0);
  const timerRef = useRef<ReturnType<typeof setInterval> | null>(null);

  const advance = useCallback(() => {
    const next = TRANSITIONS[Math.floor(Math.random() * TRANSITIONS.length)];

    setTransition(next);
    setIndex((prev) => (prev + 1) % FACTS.length);
    setKey((prev) => prev + 1);
  }, []);

  useEffect(() => {
    timerRef.current = setInterval(advance, 3000);

    return () => {
      if (timerRef.current) clearInterval(timerRef.current);
    };
  }, [advance]);

  const fact = FACTS[index];

  return (
    <div
      role="button"
      style={{
        position: "fixed",
        inset: 0,
        zIndex: 50,
        cursor: "pointer",
        background: `linear-gradient(155deg, ${fact.from}, ${fact.to})`,
        transition: "background 0.8s ease",
        display: "flex",
        flexDirection: "column",
        alignItems: "center",
        justifyContent: "center",
        padding: "32px 28px",
      }}
      tabIndex={0}
      onClick={onDismiss}
      onKeyDown={(e) => e.key === "Enter" && advance()}
    >
      {/* dot grid overlay */}
      <div
        style={{
          position: "absolute",
          inset: 0,
          opacity: 0.04,
          backgroundImage:
            "radial-gradient(circle, white 1px, transparent 1px)",
          backgroundSize: "28px 28px",
          pointerEvents: "none",
        }}
      />

      <FallingLeaves />

      {/*
       * Mascot — a welcoming presence on the attract screen, per
       * docs/planning/02-design-mandate.md SS4.6 ("the idle/attract loop —
       * a natural home for character personality"). Anchored bottom-right,
       * partially off-frame, so it reads as a companion peeking in rather
       * than competing with the rotating fact card for attention. Credit:
       * public/mascot/CREDITS.md.
       */}
      <div
        aria-hidden
        className="float-anim"
        style={{
          position: "absolute",
          bottom: -20,
          right: -30,
          width: "58vmin",
          maxWidth: 420,
          opacity: 0.92,
          pointerEvents: "none",
          filter: "drop-shadow(0 12px 28px rgba(0,0,0,0.35))",
        }}
      >
        <Image
          alt=""
          height={1000}
          src="/mascot/attract-hero.png"
          style={{ width: "100%", height: "auto" }}
          width={936}
        />
      </div>

      {/* EcoCharge brand */}
      <div
        style={{
          position: "absolute",
          top: 32,
          left: 28,
          display: "flex",
          alignItems: "center",
          gap: 8,
        }}
      >
        <span style={{ fontSize: 18 }}>🌿</span>
        <span
          style={{
            color: "rgba(255,255,255,0.45)",
            fontWeight: 700,
            fontSize: 13,
            letterSpacing: "0.05em",
          }}
        >
          EcoCharge
        </span>
      </div>

      {/* progress dots */}
      <div style={{ position: "absolute", top: 36, display: "flex", gap: 5 }}>
        {FACTS.map((_, i) => (
          <div
            key={i}
            style={{
              width: i === index ? 22 : 5,
              height: 5,
              borderRadius: 3,
              background: i === index ? fact.accent : "rgba(255,255,255,0.25)",
              transition: "all 0.35s ease",
            }}
          />
        ))}
      </div>

      {/* fact card */}
      <div
        key={key}
        className={transition}
        style={{
          textAlign: "center",
          maxWidth: 340,
          position: "relative",
          zIndex: 1,
        }}
      >
        <div
          className="float-anim"
          style={{
            fontSize: 88,
            marginBottom: 28,
            display: "inline-block",
            filter: "drop-shadow(0 4px 16px rgba(0,0,0,0.4))",
          }}
        >
          {fact.icon}
        </div>

        <h2
          style={{
            color: fact.accent,
            fontSize: 38,
            fontWeight: 800,
            letterSpacing: "-0.02em",
            marginBottom: 14,
            lineHeight: 1.1,
          }}
        >
          {fact.title}
        </h2>

        <p
          style={{
            color: "rgba(255,255,255,0.82)",
            fontSize: 18,
            lineHeight: 1.55,
            fontWeight: 400,
            maxWidth: 300,
            margin: "0 auto",
          }}
        >
          {fact.message}
        </p>
      </div>

      {/* tap hint */}
      <p
        style={{
          position: "absolute",
          bottom: 36,
          color: "rgba(255,255,255,0.35)",
          fontSize: 12,
          fontWeight: 500,
          letterSpacing: "0.12em",
          textTransform: "uppercase",
          animation: "fade-in 1s ease both 1.2s",
        }}
      >
        Tap anywhere to continue
      </p>
    </div>
  );
}
